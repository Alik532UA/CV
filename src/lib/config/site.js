/**
 * Адреса сайту — ОДНЕ джерело правди (CUSTOM-DOMAIN-v8 § анти-патерни, HIGH).
 *
 * ЧОМУ `.js`, а не `.ts`, як решта конфігів. Ці два значення потрібні трьом
 * різним споживачам, і лише один із них розуміє TypeScript:
 *
 *   - `svelte.config.js` — конфіг збірки, виконується Node до будь-якої
 *     компіляції;
 *   - `scripts/check-build.mjs` — гейт над `build/`, теж голий Node;
 *   - `SEO.svelte` і `i18n/routing.ts` — код сайту.
 *
 * Файл на `.ts` довелося б читати регуляркою з двох перших, а регулярка — це
 * той самий дубль, тільки з зайвим кроком: вона мовчки перестане збігатися при
 * першому ж переформатуванні. Простий `.js` із JSDoc імпортують УСІ троє
 * буквально, і розходитися стає нічому. `allowJs`/`checkJs` у `tsconfig.json`
 * увімкнені, тож типи тут перевіряються нарівні з рештою.
 *
 * ЩО САМЕ ЦЕ ЛАМАЛО. До цього файлу origin був виписаний тричі — у `SEO.svelte`,
 * у `check-build.mjs` і всередині `langUrl()` (там ще й base, прямо в шаблоні
 * рядка). Гейт `check-build` при цьому звіряв canonical із ВЛАСНОЮ копією
 * значення: зміни origin в одному місці — і гейт лишався зеленим, підтверджуючи
 * сам себе. Канон називає цю форму окремо: гейт мусить ЧИТАТИ значення з
 * джерела правди, а не тримати його дублікат із приміткою «мусить збігатися».
 *
 * ПЕРЕЇЗД НА ВЛАСНИЙ ДОМЕН — це правка двох рядків тут, і обидва в одному
 * коміті за побудовою: `paths.base` у `svelte.config.js` виводиться звідси ж.
 */

