// @vitest-environment node
import { describe, expect, it } from "vitest";
import { globSync, readFileSync } from "node:fs";

/**
 * Світла тема оголошує `only light` — і ніде не оголошує голе `light`.
 *
 * ## Що це стереже
 *
 * Android Chrome із темною темою САМОГО браузера має Auto Dark Theme: він
 * перемальовує в темні кольори кожну сторінку, яку вважає світлою і без власної
 * темної теми. Ознака, за якою він це вирішує, — використана схема документа, і
 * саме голе `color-scheme: light` її й оголошує. Відмова називається `only`.
 *
 * Заміряно на пристрої в сусідньому `teatralo4ka.odesa.ua` 7 вересня 2026:
 * автор надіслав знімок, де світлі теми сайту перефарбовані до невпізнання, а
 * після заміни на `only light` перемальовування зникло на тому самому телефоні.
 * Правило — UI-UX-v9 `UIUX-ONLY-LIGHT`.
 *
 * ## Чому три джерела, а не одне
 *
 * Схему присвоюють у трьох місцях: таблиця стилів, мета-тег у розмітці й
 * скрипт першого кадру (а в проєктах із контролером — ще й він). У школі гейт
 * дивився лише на `app.html` і був ЗЕЛЕНИЙ увесь час, поки скрипт рядком нижче
 * переписував значення на `light`. Тому перевірка читає всі джерела, де схема
 * взагалі може з'явитися.
 *
 * ## І ТУТ БУЛО ТЕ САМЕ, ЛИШЕ НА ТРЕТЬОМУ ДЖЕРЕЛІ
 *
 * Перелік нижче складався з `app.css` і `app.html`, тобто з ДВОХ джерел із
 * трьох, які називає правило. Третє — контролер теми — весь цей час робив
 * `document.documentElement.style.colorScheme = theme`, і цього ніхто не
 * бачив: скрипт першого кадру той самий рядок утратив разом із поясненням
 * ЧОМУ, а контролер лишився з ним.
 *
 * Наслідок заміряно в браузері, а не виведено з коду:
 * `getComputedStyle(:root).colorScheme` віддавав `light` і одразу після
 * завантаження, і після натискання світлої теми. Тобто `only light` в
 * `app.css` не діяв НІКОЛИ — інлайновий стиль перебиває таблицю стилів, — і
 * сайт весь час оголошував рівно те, за чим Android Chrome вмикає Auto Dark
 * Theme. Це той самий `PIT-NUMBER-UNDER-GATE` у формі «під гейтом одне з
 * трьох джерел, а обіцяв він усі».
 *
 * Тому перелік більше не пишеться руками: джерела ЗНАХОДЯТЬСЯ на диску за
 * згадкою схеми. Новий файл, що присвоює її, потрапляє під перевірку сам.
 *
 * ## Зворотний експеримент
 *
 * Проведено двічі: `only light` в `app.css` повернено до `light` — перевірка
 * почервоніла й назвала файл із номером рядка; рядок повернено в контролер —
 * почервоніла перевірка інлайнового присвоєння.
 */

/**
 * Усі джерела, де схема взагалі згадується: розмітка, стилі, будь-який модуль
 * чи компонент. Перелік із диска, а не константа — константа й була дірою.
 */
const ДЖЕРЕЛА = [
	"src/app.css",
	"src/app.html",
	...globSync("src/**/*.{ts,svelte}").filter(
		(ф) => !/\.(test|spec)\.ts$/.test(ф) && /colorScheme|color-scheme/.test(readFileSync(ф, "utf8"))
	)
].map((ф) => ф.replace(/\\/g, "/"));

describe("color-scheme світлої теми", () => {
	it("перевірка жива: джерела прочитано й схема в них є", () => {
		for (const ф of ДЖЕРЕЛА) {
			const текст = readFileSync(ф, "utf8");
			expect(текст.length, `${ф} порожній`).toBeGreaterThan(100);
		}
		const усе = ДЖЕРЕЛА.map((ф) => readFileSync(ф, "utf8")).join("BREAK");
		expect(усе, "жодного оголошення color-scheme — стерегти нема чого").toContain(
			"color-scheme"
		);
	});

	it("ніде немає голого `light`: ні в CSS, ні в мета-тезі, ні в скрипті", () => {
		const bad: string[] = [];
		for (const ф of ДЖЕРЕЛА) {
			readFileSync(ф, "utf8")
				.split("\n")
				.forEach((рядок, i) => {
					// Рядок, що ПРИСВОЮЄ схему: властивість CSS або значення мета-тега.
					const присвоєння = /color-scheme\s*:|colorScheme\s*=|name="color-scheme"/.test(рядок);
					if (!присвоєння) return;
					if (/(:|=)\s*["']?\s*light\s*["']?\s*;?\s*$|content="light"/.test(рядок)) {
						bad.push(`${ф}:${i + 1} — ${рядок.trim()}`);
					}
				});
		}
		expect(bad, `Auto Dark Theme перемалює світлу тему:\n${bad.join("\n")}`).toEqual([]);
	});

	it("світла тема справді звужена до `only light`", () => {
		const css = readFileSync("src/app.css", "utf8");
		expect(css, "світла тема не оголошує `only light`").toMatch(
			/data-theme=['"]light['"]\s*\][^{]*\{[^}]*color-scheme\s*:\s*only\s+light/
		);
	});

	/**
	 * Схему НІХТО не присвоює інлайновим стилем — незалежно від значення.
	 *
	 * Попередня перевірка шукає голе `light` і на `style.colorScheme = theme`
	 * сліпа за побудовою: у рядку немає жодного значення, лише змінна. А
	 * наслідок той самий і гірший — інлайновий стиль перебиває ВСЕ, тобто
	 * звуження в `app.css` стає недосяжним для будь-якої теми одразу.
	 *
	 * Тому правило тут не про значення, а про механізм: схему оголошує
	 * таблиця стилів за атрибутом `data-theme`, і жоден скрипт її не чіпає.
	 */
	it("жоден скрипт не присвоює схему інлайновим стилем", () => {
		const bad: string[] = [];
		for (const ф of ДЖЕРЕЛА) {
			readFileSync(ф, "utf8")
				.split("\n")
				.forEach((рядок, i) => {
					if (/^\s*(\/\/|\*|<!--)/.test(рядок)) return;
					if (/\.style\s*\.\s*colorScheme\s*=|setProperty\(\s*["']color-scheme["']/.test(рядок)) {
						bad.push(`${ф}:${i + 1} — ${рядок.trim()}`);
					}
				});
		}
		expect(
			bad,
			"інлайновий стиль перебиває `app.css`, і `only light` стає недосяжним:\n" +
				bad.join("\n")
		).toEqual([]);
	});
});
