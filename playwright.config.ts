import { defineConfig, devices } from '@playwright/test';

/**
 * Окремий порт саме для тестів, і свій у кожному проєкті.
 *
 * Було `5173` плюс `reuseExistingServer: !process.env.CI`. 5173 — типовий порт
 * Vite, тобто той самий в усіх сімох проєктах. Якщо на ньому вже висить
 * dev-сервер ІНШОГО проєкту, Playwright спокійно бере його й перевіряє чужий
 * застосунок: тест зелений, перевірено не те (AI-AGENT-PITFALLS-v8 § 1).
 * Це не гіпотеза — саме так інваріант унікальності `data-testid` тут одного
 * разу «пройшов», дивлячись на сусідній сайт.
 *
 * 5299, а не 5273: на 5273 сидить `Slovko`, тобто «свій порт у кожному проєкті»
 * виконувалося лише наполовину. Обидва конфіги мають `--strictPort` і
 * `reuseExistingServer: false`, тож зіткнення давало голосне падіння, а не тихо
 * перевірений чужий сайт — але саме цього правило й мало уникати. Число
 * узгоджене з `cv-dev` (5199) у `.claude/launch.json` кореневої теки.
 */
const TEST_PORT = 5299;

export default defineConfig({
	testDir: './tests',
	timeout: 30 * 1000,
	expect: {
		timeout: 5000
	},
	fullyParallel: true,
	forbidOnly: !!process.env.CI,
	retries: process.env.CI ? 2 : 0,
	/*
	 * Локально 4, а не «скільки дасть машина».
	 *
	 * `undefined` віддає Playwright половину ядер — на цій машині вісім. Поки
	 * тестів було 22, воно трималося; на 29 повний прогін почав валити чотири
	 * тести підряд — axe на головній і два сценарії AI-матчера. Жоден із них не
	 * падав поодинці, і жоден не падав із `--workers=1`: причина не в коді, а в
	 * тому, що вісім браузерів і прев'ю-сервер не вміщаються в цей процесор,
	 * а axe до того ж сам по собі важкий для CPU.
	 *
	 * Червоний прогін, причина якого не в коді, — це прогін, який починають
	 * ігнорувати (той самий аргумент, що для `off` в ESLint і нуля в axe).
	 * Заміряно на 29 тестах: вісім воркерів — 4 падіння за 3,9 хв, чотири —
	 * зелено за 1,2 хв, один — зелено за 1,6 хв. Тобто обмеження ще й швидше.
	 *
	 * У CI лишається 1: там процесор слабший, а послідовний прогін ще й дає
	 * читабельний лог падіння.
	 */
	workers: process.env.CI ? 1 : 4,
	reporter: 'html',
	use: {
		actionTimeout: 0,
		baseURL: `http://localhost:${TEST_PORT}`,
		trace: 'on-first-retry',
	},
	projects: [
		{
			name: 'chromium',
			use: { ...devices['Desktop Chrome'] },
		},
		{
			name: 'firefox',
			use: { ...devices['Desktop Firefox'] },
		},
		{
			name: 'webkit',
			use: { ...devices['Desktop Safari'] },
		},
	],
	webServer: {
		/*
		 * ПРЕВ'Ю ЗІБРАНОГО САЙТУ, а не dev-сервер (CODE-QUALITY-v8 § 5.7).
		 *
		 * Це не оптимізація, а питання того, що саме перевіряється. Dev і збірка
		 * — різні застосунки рівно в тих місцях, де живуть найдорожчі дефекти
		 * цього проєкту:
		 *
		 *   CSP        dev віддає ЗАГОЛОВОК із nonce; збірка — <meta> без нього,
		 *              тобто працює лише хеш. Політика, зламана у збірці, у dev
		 *              зелена;
		 *   розмітка   dev рендерить сторінку на запит; збірка віддає prerender
		 *              з диску. Секції, які не доїхали в prerender, у dev на
		 *              місці — саме так вони й прожили тут довго;
		 *   canonical, `sveltekit-prerender` в адресах, порожнє тіло — у dev не
		 *              відтворюються взагалі.
		 *
		 * Побічний, але не другорядний виграш: dev-сервер захлинався від 22
		 * тестів у паралель — сім падали з `net::ERR_ABORTED` на `page.goto`,
		 * бо компілював модулі під навантаженням. Прев'ю віддає готові файли.
		 *
		 * Ціна — збірка перед прогоном (~25 с). `--strictPort`: зайнятий порт
		 * мусить УПАСТИ, а не тихо з'їхати на наступний, інакше `port` нижче
		 * вказував би на чужий сервер.
		 */
		command: `npm run build && npm run preview -- --port ${TEST_PORT} --strictPort`,
		port: TEST_PORT,
		reuseExistingServer: false,
		// Збірка входить у команду, тож типових 60 с не вистачає.
		timeout: 180_000,
		env: {
			// Адреса-заглушка AI-проксі: усі запити на неї перехоплює page.route у
			// tests/ai-matcher.spec.ts, тому нічого справді слухати цей порт не має.
			// Без цієї змінної модалка одразу каже «проксі не налаштований» і тест
			// не має що перевіряти.
			PUBLIC_AI_PROXY_URL: 'http://127.0.0.1:8788'
		}
	},
});
